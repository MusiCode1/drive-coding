/**
 * speakable.ts — טקסט-מרקדאון → טקסט **בר-הקראה**.
 *
 * ─── slice tts-speakable-text ───
 *
 * 🔴 **הבעיה שדווחה מהשדה:** ה-TTS מקריא בלוקי-קוד מילה במילה, ‏URL-ים תו
 * אחר תו, ותחביר-מרקדאון כסימנים. בשיחת-קוד זה רוב התוכן.
 *
 * ⚠️ **רץ לפני פיצול-המשפטים**, ולכן הוא גם **מקצר את התור**: בלוק-קוד בן
 * 40 שורות הופך למילתיים, ולא ל-15 מקטעי-TTS שממתינים בתור. נמדד באותו יום
 * פיגור של 23 מקטעים ממתינים — זה נוגס בו ישירות.
 *
 * טהור: אפס IO, אפס Date, אפס תלות בספק. ה-labels מוזרקים כדי שהשפה תישאר
 * באחריות שכבת-ה-i18n ולא תיקבע כאן.
 */

export type SpeakableLabels = {
  /** בלוק-קוד ללא שפה מוצהרת. */
  codeBlock: string
  /** בלוק-קוד עם שפה — מקבל את השם, למשל "בלוק קוד TypeScript". */
  codeBlockWithLang: (lang: string) => string
  /** ‏URL חשוף, או קישור שאין לו טקסט. */
  link: string
  /** תמונה. */
  image: string
}

/**
 * אורך מרבי לקוד-inline שעדיין נקרא כמות שהוא. מעליו — נאמר "קוד".
 * ‏24 תווים ≈ שם-משתנה או קריאת-פונקציה קצרה; מעבר לזה ההקראה תו-אחר-תו
 * ארוכה יותר מהתועלת.
 */
const INLINE_CODE_MAX = 24

/** ‏URL חשוף — לא בתוך תחביר-קישור. */
const BARE_URL = /https?:\/\/[^\s<>()[\]]+/g

/**
 * ⚠️ **גדר חוקית חייבת לפתוח שורה.** ``` בתוך מחרוזת באמצע שורה
 * (`text.indexOf("` + "```" + `")`) **אינה** גדר — וספירתה ככזו מפרקת את כל
 * הזיווג: הבלוק הראשון נסגר מוקדם, השני נפתח באמצע קוד, והתוצאה היא גם
 * דליפת-קוד להקראה וגם בליעת טקסט תמים שביניהם. נשמע בפועל.
 */
const FENCE_LINE = /^[ \t]{0,3}```/gm

export type SpeakableOpts = {
  /**
   * ⚠️ **חובה בזרימה.** בלעדיו `toSpeakable` מסיים ב-`trim()`, ועל חוצץ
   * שגדל הוא אוכל את הרווח שלפני ה-chunk הבא — אחרי מספיק chunks המילים
   * נדבקות ("הנההסברקצר"). נמדד ב-`speakable-stream.test.ts`.
   */
  stream?: boolean
}

export function toSpeakable(text: string, labels: SpeakableLabels, opts?: SpeakableOpts): string {
  let out = text

  // ─── 1. בלוקי-קוד מגודרים ───
  // ⚠️ **ראשון, ולפני כל השאר.** בתוך בלוק-קוד יש URL-ים, כוכביות ותחביר
  // שנראה כמו מרקדאון; אם נעבד אותם קודם, נשנה טקסט שעומד להימחק ממילא,
  // ובמקרה הרע נשבור את גבול-הבלוק עצמו.
  // ⚠️ **השורות הריקות שמסביב נבלעות יחד עם הבלוק**, ולכן התווית נדבקת
  // לטקסט השכן במקום להיוותר פסקה לעצמה.
  //
  // 🔴 הסיבה **מדודה בשדה**: כשהתווית נשלחה כמקטע-TTS עצמאי ("בלוק קוד
  // typescript", בלי סימן-סיום), ‏Gemini פשוט **לא הקריא אותה**. אומת
  // בטלפון — המקטע נכנס לתור, סונתז ונוגן (`done`, אפס `skipped`) ובכל
  // זאת לא נשמע: המודל התייחס אליה כמטא-טקסט ולא כתוכן. אותה משפחה של
  // preamble-leak, בכיוון ההפוך. ⇒ כשהיא חלק ממשפט אמיתי, היא נאמרת.
  out = out.replace(
    /^[ \t]{0,3}```([^\n`]*)\n([\s\S]*?)^[ \t]{0,3}```[ \t]*$/gm,
    (_m, lang: string) => {
      const l = lang.trim().split(/\s+/)[0] ?? ""
      return l.length > 0 ? ` ${labels.codeBlockWithLang(l)} ` : ` ${labels.codeBlock} `
    },
  )
  // בלוק שנפתח ולא נסגר (זרימה חיה — הסוגר עוד לא הגיע)
  out = out.replace(/^[ \t]{0,3}```([^\n`]*)\n[\s\S]*$/m, (_m, lang: string) => {
    const l = lang.trim().split(/\s+/)[0] ?? ""
    return l.length > 0 ? ` ${labels.codeBlockWithLang(l)} ` : ` ${labels.codeBlock} `
  })

  // ⚠️ **הדבקת התווית לשכן — מעבר נפרד, ובכוונה אחרי כל הגדרות.**
  //
  // ניסיון קודם בלע את השורות הריקות **בתוך** רגקס-הגדר עצמו, וזה שבר את
  // העיגון-לשורה של הגדר **הבאה**: היא נדבקה לטקסט שלפניה, `^` הפסיק
  // להתאים, והקוד שלה דלף להקראה. ⇒ מפרידים: קודם מזהים גדרות (עיגון
  // שלם), ורק אז מדביקים.
  //
  // 🔴 ולמה בכלל: תווית לבדה בשורה הופכת למקטע-TTS עצמאי, ו-Gemini **לא
  // מקריא** פרגמנט כזה — נמדד בטלפון (נכנס לתור, סונתז, נוגן, לא נשמע).
  {
    const cb = labels.codeBlock.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    out = out.replace(new RegExp(`\\n+[ \\t]*(${cb}[^\\n]*?)[ \\t]*\\n+`, "g"), " $1 ")
  }

  // ─── 1ב. הדבקת התווית לשכן ───
  // ⚠️ **מעבר נפרד, אחרי שכל הגדרות זוהו.** בליעת השורות בתוך רגקס-הגדר
  // עצמו שברה את העיגון-לשורה של הגדר הבאה.
  //
  // 🔴 ולמה בכלל: תווית לבדה בפסקה הופכת למקטע-TTS עצמאי, ו-Gemini **אינו
  // מקריא** פרגמנט כזה — נמדד בטלפון: המקטע נכנס לתור, סונתז, נוגן
  // (`done`, אפס `skipped`), ובכל זאת לא נשמע. כשהיא חלק ממשפט — נאמרת.
  //
  // בטוח כאן דווקא מפני שהתוצאה **אינה חוזרת לחוצץ** (ר' `splitStreamable`).
  {
    const cb = labels.codeBlock.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    out = out.replace(new RegExp(`\\n+[ \\t]*(${cb}[^\\n]*?)[ \\t]*(\\n+|$)`, "g"), " $1 ")
  }

  // ─── 2. תמונות — לפני קישורים, כי התחביר שלהן מכיל תחביר-קישור ───
  out = out.replace(/!\[([^\]]*)\]\([^)]*\)/g, (_m, alt: string) =>
    alt.trim().length > 0 ? ` ${labels.image}: ${alt.trim()} ` : ` ${labels.image} `,
  )

  // ─── 3. קישורים — הטקסט נקרא, ה-URL נזרק ───
  out = out.replace(/\[([^\]]*)\]\([^)]*\)/g, (_m, label: string) =>
    label.trim().length > 0 ? label.trim() : ` ${labels.link} `,
  )

  // ─── 4. קוד-inline ───
  out = out.replace(/`([^`\n]+)`/g, (_m, code: string) =>
    code.length <= INLINE_CODE_MAX ? code : ` ${labels.codeBlock} `,
  )

  // ─── 5. URL חשוף ───
  out = out.replace(BARE_URL, ` ${labels.link} `)

  // ─── 6. סימוני-הדגשה ותחביר-כותרת ───
  // ⚠️ רק הסימנים יורדים, **הטקסט נשאר** — זו הקראה, לא תקציר.
  out = out.replace(/^\s{0,3}#{1,6}\s+/gm, "")
  out = out.replace(/^\s{0,3}>\s?/gm, "")
  out = out.replace(/(\*\*|__)(.+?)\1/g, "$2")
  out = out.replace(/(\*|_)(?!\s)(.+?)(?<!\s)\1/g, "$2")
  out = out.replace(/~~(.+?)~~/g, "$1")

  // ─── 7. ניקוי רווחים שנוצרו מההחלפות ───
  out = out.replace(/[ \t]{2,}/g, " ")
  // התוויות מוזרקות עם רווחים משני צדדיהן (כדי לא להידבק למילה קודמת);
  // ליד שורה-חדשה הרווח הזה מיותר ונשמע כהיסוס.
  out = out.replace(/[ \t]+\n/g, "\n")
  out = out.replace(/\n[ \t]+/g, "\n")
  out = out.replace(/\n{3,}/g, "\n\n")
  // ⚠️ בזרימה **אין** trim — ר' SpeakableOpts.stream.
  return opts?.stream === true ? out : out.trim()
}

/**
 * מפריד טקסט-**גולמי** זורם לחלק בטוח-לעיבוד ולחלק שיש להחזיק.
 *
 * ─── slice tts-speakable-text ───
 *
 * 🔴 **שני כללים, ושניהם נלמדו בדם.**
 *
 * 1. **גדר פתוחה מוחזקת.** בלוק-קוד מגיע פרוס על עשרות chunks; אם המפצל
 *    יראה את תוכנו לפני שהגדר נסגרה, נקודות ושורות שבתוך הקוד ייחתכו
 *    כמשפטים וייצאו להקראה. נשמע בפועל.
 *
 * 2. **שורה חלקית מוחזקת.** כל שאר תחביר-המרקדאון (קישור, תמונה,
 *    קוד-inline) **אינו חוצה שורות** — ולכן עיבוד של טקסט שנחתך באמצע
 *    שורה מפרק אותו לחצאים ומשאיר סוגריים חשופים בהקראה.
 *
 * ⚠️ **וזה מה שמאפשר לחוצץ להישאר גולמי.** הניסיון הקודם החזיר טקסט
 * *מעובד* לחוצץ ואז עיבד אותו שוב — וכל סיבוב שבר מבנה במקום אחר
 * (‏trim אכל רווחים, שרשור איבד את העיגון-לשורה של הגדר הבאה, וכן הלאה).
 * כאן כל קטע-גולמי מעובד **בדיוק פעם אחת**, והתוצאה לעולם לא חוזרת.
 */
export function splitStreamable(text: string): { ready: string; held: string } {
  const fences: number[] = []
  FENCE_LINE.lastIndex = 0
  for (;;) {
    const m = FENCE_LINE.exec(text)
    if (m === null) break
    fences.push(m.index + (m[0].length - 3))
  }

  // (1) גדר לא-מזווגת — מחזיקים ממנה והלאה.
  if (fences.length % 2 === 1) {
    const open = fences[fences.length - 1] as number
    return { ready: text.slice(0, open), held: text.slice(open) }
  }

  // (2) 🔴 **הגדר הסוגרת הגיעה אבל שורתה טרם נסגרה.**
  //
  // זה המקרה שהפיל את הכול כשה-ACP שולח **תו בכל פעם** (קורה בשטח).
  // החיתוך "עד השורה-החדשה האחרונה" נפל אז **בתוך הבלוק**: ‏`ready` יצא עם
  // מספר גדרות אי-זוגי, ענף הגדר-הפתוחה בלע ממנו והלאה (`[\s\S]*$`),
  // והגדר-הסוגרת נשארה ב-`held` והתחזתה שם ל**פותחת** — ומכאן תוויות
  // כפולות וטקסט שנעלם.
  //
  // ⇒ אם אחרי הגדר האחרונה אין עדיין שורה-חדשה, מחזיקים מה**פותחת** שלה.
  if (fences.length > 0) {
    const lastFence = fences[fences.length - 1] as number
    if (text.indexOf("\n", lastFence) === -1) {
      const open = fences[fences.length - 2] as number
      return { ready: text.slice(0, open), held: text.slice(open) }
    }
  }

  // (3) שורה חלקית — מחזיקים **רק אם יש בה תחביר פתוח**.
  //
  // 🔴 גרסה קודמת החזיקה כל שורה חלקית, וזו הייתה רגרסיה קשה: הודעה
  // חד-פסקתית **אין בה `\n` עד הסוף**, ולכן שום דבר לא הוקרא עד סוף-התור.
  // נתפס ע"י `speaker.test.svelte.ts` (‏markReady נקרא 0 פעמים).
  //
  // ⇒ מה שבאמת צריך הגנה הוא **תחביר שנחתך באמצע**: קוד-inline, קישור
  //   או תמונה שטרם נסגרו. עיבודם כחצי היה משאיר סוגריים חשופים בהקראה.
  //   שורה בלי תחביר פתוח בטוחה לחלוטין, ומזרימה מיָדית.
  const nl = text.lastIndexOf("\n")
  const tail = nl === -1 ? text : text.slice(nl + 1)
  // ⚠️ שורה שמתחילה בגרש-אחורי היא **או** קוד-inline **או** גדר שטרם
  // הושלמה (``` בדרך). שתיהן חייבות להיסגר לפני עיבוד: שתי גרשיים בלבד
  // אינן מזוהות כגדר, עוברות הלאה, והגדר נחתכת לשניים — הקוד דלף.
  const startsBacktick = /^[ \t]{0,3}`/.test(tail)
  const openInline = startsBacktick || (tail.match(/`/g)?.length ?? 0) % 2 === 1
  const lastOpen = Math.max(tail.lastIndexOf("["), tail.lastIndexOf("!["))
  const openLink = lastOpen !== -1 && !/\]\([^)]*\)/.test(tail.slice(lastOpen))
  if (!openInline && !openLink) return { ready: text, held: "" }
  if (nl === -1) return { ready: "", held: text }
  return { ready: text.slice(0, nl + 1), held: tail }
}
